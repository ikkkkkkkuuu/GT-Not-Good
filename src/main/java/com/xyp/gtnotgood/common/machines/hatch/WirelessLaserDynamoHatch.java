package com.xyp.gtnotgood.common.machines.hatch;

import net.minecraft.util.StatCollector;

import org.apache.commons.lang3.ArrayUtils;

import com.gtnewhorizon.gtnhlib.util.numberformatting.NumberFormatUtil;
import com.xyp.gtnotgood.utils.text.EnergyHatchTooltip;

import gregtech.api.enums.GTValues;
import gregtech.api.interfaces.ITexture;
import gregtech.api.interfaces.metatileentity.IMetaTileEntity;
import gregtech.api.interfaces.tileentity.IGregTechTileEntity;
import gregtech.api.metatileentity.MetaTileEntity;
import gregtech.common.misc.WirelessNetworkManager;
import tectech.thing.metaTileEntity.hatch.MTEHatchWirelessDynamoMulti;

@IMetaTileEntity.SkipGenerateName
@IMetaTileEntity.SkipGenerateDescription
public final class WirelessLaserDynamoHatch extends MTEHatchWirelessDynamoMulti {

    public WirelessLaserDynamoHatch(int id, String name, int tier, int amperes) {
        super(id, name, "", tier, amperes);
    }

    private WirelessLaserDynamoHatch(String name, int tier, int amperes, String[] description,
        ITexture[][][] textures) {
        super(name, tier, amperes, description, textures);
    }

    @Override
    public String getLocalName() {
        // #tr gtng.wireless.laser.output.name
        // # %1$s %2$sA Wireless Laser Dynamo Hatch
        // # zh_CN %2$s安%1$s无线激光动力仓
        return StatCollector.translateToLocalFormatted("gtng.wireless.laser.output.name", GTValues.VN[mTier],
            NumberFormatUtil.formatNumber(maxAmperes));
    }

    @Override
    public String[] getDescription() {
        // #tr gtng.wireless.laser.output.description
        // # Sends EU generated by a multiblock to the owner's GT wireless network
        // # zh_CN 将多方块机器产生的 EU 存入仓主的 GT 无线电网
        String description = StatCollector.translateToLocal("gtng.wireless.laser.output.description");
        String[] details = EnergyHatchTooltip.format(description, true, mTier, maxAmperes);
        // #tr gtng.wireless.laser.output.capacity
        // # Internal energy capacity: %s EU
        // # zh_CN 内部能量容量：%s EU
        String capacity = StatCollector.translateToLocalFormatted("gtng.wireless.laser.output.capacity",
            NumberFormatUtil.formatNumber(maxEUStore()));
        // #tr gtng.wireless.laser.output.network
        // # Uploads stored EU every %s ticks; does not power cables
        // # zh_CN 每 %s tick 将缓存 EU 存入电网；不向线缆供电
        String network = StatCollector.translateToLocalFormatted("gtng.wireless.laser.output.network",
            NumberFormatUtil.formatNumber(WirelessNetworkManager.ticks_between_energy_addition));
        return ArrayUtils.addAll(details, capacity, network);
    }

    @Override
    public MetaTileEntity newMetaEntity(IGregTechTileEntity tile) {
        return new WirelessLaserDynamoHatch(mName, mTier, maxAmperes, mDescriptionArray, mTextures);
    }
}
