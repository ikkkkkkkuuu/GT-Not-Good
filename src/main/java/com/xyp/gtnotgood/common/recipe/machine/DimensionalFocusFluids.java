package com.xyp.gtnotgood.common.recipe.machine;

import net.minecraftforge.fluids.Fluid;
import net.minecraftforge.fluids.FluidStack;

import com.xyp.gtnotgood.utils.enums.ModList;

import gregtech.api.enums.FluidState;
import gregtech.api.fluid.GTFluidFactory;

public final class DimensionalFocusFluids {

    private static Fluid photoresist;
    private static Fluid euvPhotoresist;

    private DimensionalFocusFluids() {}

    public static void init() {
        if (photoresist != null) return;
        // #tr fluid.gtnotgood.photoresist
        // # Photoresist
        // # zh_CN 光刻胶
        photoresist = GTFluidFactory.builder(ModList.GTNotGood.getID() + ".photoresist")
            .withDefaultLocalName("Photoresist").withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 222, 180, 40, 255 }).withStateAndTemperature(FluidState.LIQUID, 300)
            .buildAndRegister().asFluid();
        // #tr fluid.gtnotgood.euv_photoresist
        // # EUV Photoresist
        // # zh_CN 极紫外光刻胶
        euvPhotoresist = GTFluidFactory.builder(ModList.GTNotGood.getID() + ".euv_photoresist")
            .withDefaultLocalName("EUV Photoresist").withTextureName("molten.autogenerated")
            .withColorRGBA(new short[] { 140, 90, 218, 255 }).withStateAndTemperature(FluidState.LIQUID, 300)
            .buildAndRegister().asFluid();
    }

    public static FluidStack photoresist(int amount) {
        return new FluidStack(photoresist, amount);
    }

    public static FluidStack euvPhotoresist(int amount) {
        return new FluidStack(euvPhotoresist, amount);
    }
}
